def build_fallback_bank(subject_code: str, topic_name: str, topic_id: int) -> list[dict]:
    """Build 10 fallback rows for a topic using subject-specific or generic template."""
    fn = SUBJECT_TEMPLATES.get(subject_code)
    if fn is None:
        return _generic_template(subject_code, topic_name, topic_id)
    return fn(topic_name, topic_id)


# === Runner ===============================================================


def run(*, dry_run: bool = False) -> dict:
    """Build fallback banks for all non-math/algebra/geom topics in the DB."""
    from app.db.session import Base, SessionLocal, engine
    from app.subjects.scripts_seed_runner import seed_for_tests
    from app.teacher import content_registry
    from app.subjects import models
    from sqlalchemy import select

    # Seed DB if needed (idempotent — drops nothing in test env without drop_all).
    Base.metadata.create_all(engine)
    sess = SessionLocal()
    try:
        seed_for_tests(sess)
    except Exception:
        # Already seeded.
        sess.rollback()
    finally:
        sess.close()

    sess = SessionLocal()
    updated: dict[str, int] = {}
    try:
        topics = sess.execute(
            select(models.Topic).join(models.Section).join(models.Subject)
        ).scalars().all()
        for t in topics:
            code = t.section.subject.code
            rows = build_fallback_bank(code, t.name, t.id)
            if not dry_run:
                content_registry.set_fallbacks(t.id, rows)
            updated[f"{code}:{t.id}"] = len(rows)
    finally:
        sess.close()

    return {
        "dry_run": dry_run,
        "topics_updated": len(updated),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    print(json.dumps(run(dry_run=args.dry_run), ensure_ascii=False))