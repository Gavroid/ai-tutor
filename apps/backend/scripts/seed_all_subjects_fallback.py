# === Generic helper ======================================================


def _rng(topic_id: int, variant_idx: int) -> random.Random:
    seed = f"s2-fallback-{topic_id}-{variant_idx}".encode("utf-8")
    digest = hashlib.sha256(seed).digest()
    return random.Random(int.from_bytes(digest[:8], "big"))


def _rotate(options: list[str], rng: random.Random) -> list[str]:
    out = list(options)
    rng.shuffle(out)
    return out


def _row(question: str, options: list[str], correct: str, explanation: str, mistakes: list[str], *, topic_id: int, variant_idx: int) -> dict:
    rng = _rng(topic_id, variant_idx)
    rotated = _rotate(options, rng)
    return {
        "question_text": question,
        "type": "single",
        "options": rotated,
        "correct_answer": correct,
        "explanation": explanation,
        "typical_mistakes": mistakes,
        "difficulty": ((variant_idx - 1) % 5) + 1,
        "order_index": variant_idx,
        "is_active": True,
    }


def _make_n_options(correct: str, distractors: list[str], topic_id: int, variant_idx: int) -> list[str]:
    """Build 4 options list = correct + 3 unique distractors, randomized.

    Drops any distractor that equals the correct answer or duplicates another
    distractor (preserving first occurrence). This is a defensive guard against
    future template edits that may accidentally include the correct answer
    in the distractor pool.
    """
    options = [correct]
    seen = {correct}
    for d in distractors:
        if d in seen:
            continue
        seen.add(d)
        options.append(d)
        if len(options) == 4:
            break
    return _rotate(options, _rng(topic_id, variant_idx))


