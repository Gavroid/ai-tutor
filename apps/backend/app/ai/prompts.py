def hint_system_at_level(level: int = 1, error_type: str | None = None) -> str:
    """Sprint 7.4 — 3 уровня подсказок.

    Уровень 1: наводящий вопрос (минимальная помощь).
    Уровень 2: подсказка к решению (без ответа).
    Уровень 3: полный разбор / объяснение.

    Ученик НЕ получает ответ напрямую — только намёк, чтобы сам додумал.

    Sprint 4.3.2: error_type (опционально) делает подсказку context-aware:
    - ARITHMETIC: фокус на перепроверке вычислений
    - CONCEPTUAL: фокус на определении/формуле
    - LOGIC: фокус на выборе правильного подхода
    - CARELESS: фокус на внимательности (без переобъяснения)
    """
    # Sprint 4.3.2: context-aware префикс по типу ошибки.
    error_prefix = ""
    if error_type == "ARITHMETIC":
        error_prefix = "\n\n⚠️ Контекст: ошибка арифметическая. Ученик вероятно знает алгоритм, но ошибся в вычислениях. Подсказка должна помочь ПЕРЕПРОВЕРИТЬ вычисления, не объяснять концепцию заново."
    elif error_type == "CONCEPTUAL":
        error_prefix = "\n\n⚠️ Контекст: ученик не понимает концепцию. Подсказка должна НАПОМНИТЬ ключевое определение или свойство, не давать ответ напрямую."
    elif error_type == "LOGIC":
        error_prefix = "\n\n⚠️ Контекст: ошибка в выборе подхода. Подсказка должна намекнуть на ПРАВИЛЬНЫЙ АЛГОРИТМ или формулу, не объяснять всё заново."
    elif error_type == "CARELESS":
        error_prefix = "\n\n⚠️ Контекст: ученик вероятно знает как решить, но ошибся по невнимательности. Подсказка должна быть КОРОТКОЙ (проверь ещё раз) — не давать полный разбор, это фрустрирует."

    if level == 1:
        return (
            BASE_SYSTEM
            + error_prefix
            + "\n\nРЕЖИМ: ПОДСКАЗКА (уровень 1 из 3). Задай ученику один наводящий вопрос, "
            + "который поможет ему самому найти решение. Не давай ответа. "
            + "Пример: 'Что произойдёт, если...?', 'На что похожа эта задача?', "
            + "'Какое свойство ты уже знаешь, что может помочь?'"
        )
    if level == 2:
        return (
            BASE_SYSTEM
            + error_prefix
            + "\n\nРЕЖИМ: ПОДСКАЗКА (уровень 2 из 3). Дай подсказку к решению — "
            + "ключевой шаг или формулу, НЕ давай финальный ответ. "
            + "Пример: 'Тебе понадобится формула ...', 'Сначала найди ...'"
        )
    if level == 3:
        return (
            BASE_SYSTEM
            + error_prefix
            + "\n\nРЕЖИМ: РАЗБОР (уровень 3 из 3). Покажи пошаговое решение с пояснением. "
            + "Ученик всё ещё должен сам записать ответ, но логика решения должна быть "
            + "полностью раскрыта."
        )
    # fallback на уровень 1
    return hint_system_at_level(1, error_type=error_type)


def check_answer_system(question_text: str, correct_answer: str, user_answer: str) -> str:
    return (
        BASE_SYSTEM
        + "\n\nРЕЖИМ: ПРОВЕРКА ОТВЕТА."
        + f"\nЗадание: {question_text}"
        + f"\nЭталонный ответ: {correct_answer}"
        + f"\nОтвет ученика: {user_answer}"
        + "\n\nВерни СТРОГО JSON без markdown-блоков и пояснений вокруг:"
        + ' {"is_correct": bool, "score": float от 0 до 1, '
        + ' "first_error": string|null, "explanation": string, '
        + ' "hint_level": int от 1 до 3, "next_difficulty": int от 1 до 5, '
        # Sprint 4.3.1: AI классифицирует тип ошибки для context-aware hints.
        + ' "error_type": "ARITHMETIC"|"CONCEPTUAL"|"LOGIC"|"CARELESS"|null}.'
        + "\n\nТип ошибки:"
        + "\n- ARITHMETIC: арифметическая ошибка в вычислениях (например 2+2=5)"
        + "\n- CONCEPTUAL: не понимает концепцию (например не знает что такое процент)"
        + "\n- LOGIC: логическая ошибка (применил не ту формулу или алгоритм)"
        + "\n- CARELESS: опечатка / невнимательность (правильный ход мысли, но ошибся в записи)"
        + "\n- null: если ответ правильный или невозможно классифицировать"
    )


def _get_rag_context_for_topic(topic_id: int | None) -> str:
    """Sprint 2026-08-22 P11: top-1 RAG chunk text для topic.

    Возвращает первое содержательное предложение из импортированных
    RagChunk для этого topic_id. Используется в generate_exercise_system
    чтобы дать LLM контекст реального учебника при генерации упражнений.
    """
    if topic_id is None:
        return ""
    try:
        from app.db.session import SessionLocal
        from app.rag_models import LearningMaterial, RagChunk
        sess = SessionLocal()
        try:
            chunk = sess.query(RagChunk).join(
                LearningMaterial, RagChunk.material_id == LearningMaterial.id
            ).filter(
                LearningMaterial.topic_id == topic_id,
                RagChunk.text.isnot(None),
                RagChunk.text != "",
            ).order_by(RagChunk.id.asc()).first()
            if chunk and chunk.text:
                import re as _re
                for sent in _re.split(r"[.!?\n]+", chunk.text):
                    sent = sent.strip()
                    if len(sent) >= 40:
                        return sent[:400]
                return chunk.text[:400]
            return ""
        finally:
            sess.close()
    except Exception:
        return ""


def generate_exercise_system(
    subject_name: str,
    topic_name: str,
    difficulty: int,
    topic_id: int | None = None,
) -> str:
    base = (
        BASE_SYSTEM
        + f"\n\nРЕЖИМ: ГЕНЕРАЦИЯ ЗАДАНИЯ. Предмет «{subject_name}», тема «{topic_name}», сложность {difficulty}/5."
    )
    # Sprint 2026-08-22 P11: добавить RAG context если есть импортированные chunks.
    rag = _get_rag_context_for_topic(topic_id)
    if rag:
        base += f"\n\nКОНТЕКСТ ИЗ УЧЕБНИКА: «{rag}».\nСформулируй задание НА ОСНОВЕ этого фрагмента."
    base += (
        "\nВерни СТРОГО JSON без markdown-блоков:"
        + ' {"question_text": string, "type": "single"|"multiple"|"numeric"|"text"|"fill"|"code",'
        + ' "options": [string]?|null, "correct_answer": string, "explanation": string,'
        + ' "typical_mistakes": [string]}.'
    )
    return base


def quiz_system(subject_name: str, topic_name: str, difficulty: int, count: int) -> str:
    """Системный промпт для генерации набора разнотипных вопросов (квиза).

    LLM возвращает СТРОГО JSON: {"questions": [<объект_вопроса>]} без markdown-блоков.
    Каждый вопрос: {"question_text", "type", "options", "correct_answer", "explanation"}.
    В quiz допускаются ТОЛЬКО типы single/multiple/numeric/text (без fill/code).
    """
    return (
        BASE_SYSTEM
        + f"\n\nРЕЖИМ: ГЕНЕРАЦИЯ КВИЗА. Предмет «{subject_name}», тема «{topic_name}», "
        + f"сложность {difficulty}/5, количество вопросов: {count}."
        + "\nСгенерируй набор разнообразных вопросов для проверки знаний по теме. "
        + "Чередуй типы вопросов (single/multiple/numeric/text), чтобы квиз был интересным."
        + "\nВерни СТРОГО JSON без markdown-блоков и пояснений вокруг:"
        + ' {"questions": [<объект_вопроса>]}.'
        + "\nКаждый элемент массива — объект вида:"
        + ' {"question_text": string,'
        + ' "type": "single"|"multiple"|"numeric"|"text",'
        + ' "options": [string]?|null,'
        + ' "correct_answer": string,'
        + ' "explanation": string}.'
        + "\nПравила по типам:"
        + "\n- \"single\": один правильный вариант; options обязателен (>=2 элементов); correct_answer — строка-вариант из options."
        + "\n- \"multiple\": несколько правильных; options обязателен (>=2 элементов); correct_answer — строка с правильными вариантами через запятую."
        + "\n- \"numeric\": числовой ответ; options=null; correct_answer — строка с числом."
        + "\n- \"text\": свободный ответ; options=null; correct_answer — эталонный короткий ответ."
        + f"\nСгенерируй ровно {count} вопросов."
    )
